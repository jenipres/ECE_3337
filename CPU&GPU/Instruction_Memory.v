`timescale 1ns / 1ps

module Instruction_Memory(
    input  wire [15:0] addr,
    output wire [15:0] instruction
);

    reg [15:0] memory [0:255];
    integer i;

    initial begin
        memory[0]  = 16'b0001_011_000_011111; // 0 - 2 Set R3 = GPU base 
        memory[1]  = 16'b0001_011_011_011111;
        memory[2]  = 16'b0001_011_011_000010;

        memory[3]  = 16'b0001_001_000_011111; // 3 - 5 set set R1 = player X
        memory[4]  = 16'b0001_001_001_011111;
        memory[5]  = 16'b0001_001_001_010010;

        memory[6]  = 16'b0001_010_000_011111; // 6 - 13 set R2 = player Y
        memory[7]  = 16'b0001_010_010_011111;
        memory[8]  = 16'b0001_010_010_011111;
        memory[9]  = 16'b0001_010_010_011111;
        memory[10] = 16'b0001_010_010_011111;
        memory[11] = 16'b0001_010_010_011111;
        memory[12] = 16'b0001_010_010_011111;
        memory[13] = 16'b0001_010_010_000011;

        memory[14] = 16'b0001_110_000_011111; // 14 - 17 set Helper constant 
        memory[15] = 16'b0001_110_110_011111;
        memory[16] = 16'b0001_110_110_011111;
        memory[17] = 16'b0001_110_110_000011;

        memory[18] = 16'b0001_100_000_000000; // 18 clear/INIT register 

        memory[19] = 16'b0011_001_011_000000; // 19 I/0 register interface 
        memory[20] = 16'b0011_000_011_000100; // crouch = 0   [R3+4] = R0 // xNOP (preserve addresses, do NOT zero x_hi)
        memory[21] = 16'b0011_010_011_000010; // y
        memory[22] = 16'b0011_100_011_000011; // pose

        memory[23] = 16'b0010_101_000_000000;
        memory[24] = 16'b0101_000_101_000001;
        memory[25] = 16'b0110_000000011101;

        memory[26] = 16'b0001_101_101_111111;
        memory[27] = 16'b0011_101_000_000000;
        memory[28] = 16'b0110_000001010010;

        memory[29] = 16'b0010_111_110_000000;
        memory[30] = 16'b1010_111_111_001000;
        memory[31] = 16'b0101_000_111_000001;
        memory[32] = 16'b0110_000000100011;
        memory[33] = 16'b0001_100_000_000001;
        memory[34] = 16'b0011_100_011_000100; // crouch

        memory[35] = 16'b0010_111_110_000000;
        memory[36] = 16'b1010_111_111_000010;
        memory[37] = 16'b0101_000_111_000001;
        memory[38] = 16'b0110_000000101110;

        // RIGHT move block -> jump to subroutine at 130
        memory[39] = 16'b0110_000010000010;   // jump 130
        memory[40] = 16'b0000_000_000_000000; // NOP
        memory[41] = 16'b0000_000_000_000000; // NOP
        memory[42] = 16'b0000_000_000_000000; // NOP
        memory[43] = 16'b0000_000_000_000000; // NOP
        memory[44] = 16'b0000_000_000_000000; // NOP
        memory[45] = 16'b0000_000_000_000000; // NOP

        memory[46] = 16'b0010_111_110_000000; // 46 - 49 Movement Control Block 
        memory[47] = 16'b1010_111_111_000001;
        memory[48] = 16'b0101_000_111_000001;
        memory[49] = 16'b0110_000000111001;

        // LEFT move block -> jump to subroutine at 140
        memory[50] = 16'b0110_000010001100;   // 50 jumps to movment subroutine 
        memory[51] = 16'b0000_000_000_000000; // NOP
        memory[52] = 16'b0000_000_000_000000; // NOP
        memory[53] = 16'b0000_000_000_000000; // NOP
        memory[54] = 16'b0000_000_000_000000; // NOP
        memory[55] = 16'b0000_000_000_000000; // NOP
        memory[56] = 16'b0000_000_000_000000; // NOP

        memory[57] = 16'b0010_111_110_000000; // 57 - 60 Movement Control block 
        memory[58] = 16'b1010_111_111_000100;
        memory[59] = 16'b0101_000_111_000001;
        memory[60] = 16'b0110_000001010010;

        memory[61] = 16'b0001_100_000_000010;
        memory[62] = 16'b0011_100_011_000011; // pose
        memory[63] = 16'b0001_010_010_100001;
        memory[64] = 16'b0011_010_011_000010; // y

        memory[65] = 16'b0001_100_000_011111;
        memory[66] = 16'b0001_101_000_011111;
        memory[67] = 16'b0001_101_101_111111;
        memory[68] = 16'b0101_000_101_111110;
        memory[69] = 16'b0001_100_100_111111;
        memory[70] = 16'b0101_000_100_111100;

        memory[71] = 16'b0001_100_000_011111;
        memory[72] = 16'b0001_101_000_011111;
        memory[73] = 16'b0001_101_101_111111;
        memory[74] = 16'b0101_000_101_111110;
        memory[75] = 16'b0001_100_100_111111;
        memory[76] = 16'b0101_000_100_111100;

        memory[77] = 16'b0001_010_010_011111;
        memory[78] = 16'b0011_010_011_000010; // y
        memory[79] = 16'b0001_101_000_001000;
        memory[80] = 16'b0011_101_000_000000;
        memory[81] = 16'b0110_000001010010;

        memory[82] = 16'b0001_100_000_011111;
        memory[83] = 16'b0001_101_000_011111;
        memory[84] = 16'b0001_101_101_111111;
        memory[85] = 16'b0101_000_101_111110;
        memory[86] = 16'b0001_100_100_111111;
        memory[87] = 16'b0101_000_100_111100;

        memory[88] = 16'b0001_100_000_011111;
        memory[89] = 16'b0001_101_000_011111;
        memory[90] = 16'b0001_101_101_111111;
        memory[91] = 16'b0101_000_101_111110;
        memory[92] = 16'b0001_100_100_111111;
        memory[93] = 16'b0101_000_100_111100;

        memory[94] = 16'b0001_100_000_011111;
        memory[95] = 16'b0001_101_000_011111;
        memory[96] = 16'b0001_101_101_111111;
        memory[97] = 16'b0101_000_101_111110;
        memory[98] = 16'b0001_100_100_111111;
        memory[99] = 16'b0101_000_100_111100;

        // Keep the original loopback
        memory[100] = 16'b0110_000000010010;   // jump back to 18

        // 101..129 unused for now
        for (i = 101; i < 130; i = i + 1)
            memory[i] = 16'b0;
        memory[130] = 16'b0001_001_001_000001; // R1 = R1 + 1
        memory[131] = 16'b0101_000_001_000011; // if R1 != 0 skip hi increment
        memory[132] = 16'b0010_100_011_000001; // R4 = [R3+1] (x_hi)
        memory[133] = 16'b0001_100_100_000001; // R4 = R4 + 1
        memory[134] = 16'b0011_100_011_000001; // [R3+1] = R4

        memory[135] = 16'b0001_100_000_000001; // R4 = 1
        memory[136] = 16'b0011_100_011_000011; // pose = 1
        memory[137] = 16'b0001_101_000_001000; // R5 = 8
        memory[138] = 16'b0011_101_000_000000; // RAM[0] = 8
        memory[139] = 16'b0110_000001010010;   // jump 82

        memory[140] = 16'b0101_000_001_000011; // if R1 != 0 skip hi decrement
        memory[141] = 16'b0010_100_011_000001; // R4 = [R3+1] (x_hi)
        memory[142] = 16'b0001_100_100_111111; // R4 = R4 - 1
        memory[143] = 16'b0011_100_011_000001; // [R3+1] = R4

        memory[144] = 16'b0001_001_001_111111; // R1 = R1 - 1
        memory[145] = 16'b0001_100_000_000001; // R4 = 1
        memory[146] = 16'b0011_100_011_000011; // pose = 1
        memory[147] = 16'b0001_101_000_001000; // R5 = 8
        memory[148] = 16'b0011_101_000_000000; // RAM[0] = 8
        memory[149] = 16'b0110_000001010010;   // jump 82

        for (i = 150; i < 256; i = i + 1)
            memory[i] = 16'b0;
    end

    assign instruction = memory[addr[7:0]];

endmodule